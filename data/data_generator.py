def generate_csv(output_path: str):
    """Training data CSV file তৈরি করে।"""
    rows = []
    for intent, sentences in TRAINING_DATA.items():
        for sentence in sentences:
            rows.append({"text": sentence, "intent": intent})

    # Shuffle করো যাতে ডাটা mixed থাকে
    random.seed(42)
    random.shuffle(rows)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "intent"])
        writer.writeheader()
        writer.writerows(rows)

    return rows


